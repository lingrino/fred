import AppKit
import FredCore
import ImageIO
import UniformTypeIdentifiers

/// Clipboard history: watches the pasteboard, stores clips, and runs the ⌥⇧C panel.
///
/// Watching: there is no pasteboard change notification on macOS, so `changeCount` is
/// polled (cheap metadata read; does not trigger pasteboard-privacy alerts). Contents are
/// read only when the count changes and the item isn't marked concealed/transient
/// (password managers, nspasteboard.org markers).
@MainActor
final class ClipboardController: NSObject, NSTextFieldDelegate {
    let store: ClipStore
    let engine: Engine
    let panel = FloatingPanel(width: ClipTheme.width)
    let field = SearchField()
    let list = ResultList(capacity: ClipTheme.visibleRows, rowHeight: ClipTheme.rowHeight, width: ClipTheme.listWidth)
    let preview = ClipPreview(frame: .zero)
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var results: [Int] = []
    private var selected = 0
    private var offset = 0
    let searchLatency = LatencyLog("clip search")
    private let io = DispatchQueue(label: "fred.clip.io", qos: .utility)

    static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    static let remoteType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

    init(engine: Engine) {
        self.engine = engine
        store = ClipStore(dir: Engine.dataDir)
        super.init()
        buildUI()
    }

    // MARK: Monitoring

    func startMonitoring() {
        let t = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = 0.05
        RunLoop.main.add(t, forMode: .common)
        timer = t
        // Daily-ish pruning of >90-day-old clips.
        let p = Timer(timeInterval: 3600, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { _ = self?.store.prune(now: UInt32(Date().timeIntervalSince1970)) }
        }
        RunLoop.main.add(p, forMode: .common)
    }

    private func poll() {
        let pb = NSPasteboard.general
        let c = pb.changeCount
        guard c != lastChange else { return }
        lastChange = c
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        guard let types = pb.types, !types.isEmpty else { return }
        for t in types where Self.skipTypes.contains(t.rawValue) { return }
        let source = pb.string(forType: Self.sourceType) ?? NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let now = UInt32(Date().timeIntervalSince1970)
        let isRemote = types.contains(Self.remoteType)

        if types.contains(.fileURL) {
            if isRemote { return }   // user's preference: ignore file lists from other devices
            let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            guard !urls.isEmpty else { return }
            let text = urls.map(\.path).joined(separator: "\n")
            store.add(kind: .files, text: text, hash: ClipStore.hash(text, kind: .files), app: source, time: now)
            return
        }
        let hasString = types.contains(.string)
        if !hasString, let (data, type) = imageData(pb, types) {
            io.async { [weak self] in
                guard let self else { return }
                let h = data.withUnsafeBytes { ClipStore.hash($0, seed: 1) }
                guard let (png, w, hgt) = Self.pngAndSize(data, type: type) else { return }
                let url = self.store.imagesDir!.appendingPathComponent(String(format: "%016llx.png", h))
                if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
                DispatchQueue.main.async {
                    MainActor.assumeIsolated {
                        self.store.add(kind: .image, text: "Image \(w)×\(hgt)", hash: h, app: source, time: now)
                    }
                }
            }
            return
        }
        if let s = pb.string(forType: .string), !s.isEmpty,
           !s.allSatisfy({ $0.isWhitespace }) {
            store.add(kind: .text, text: s, hash: ClipStore.hash(s, kind: .text), app: source, time: now)
        }
    }

    private func imageData(_ pb: NSPasteboard, _ types: [NSPasteboard.PasteboardType]) -> (Data, NSPasteboard.PasteboardType)? {
        for t in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(t) {
            if let d = pb.data(forType: t) { return (d, t) }
        }
        return nil
    }

    /// Keeps PNG as-is; converts anything else (TIFF) to PNG. Returns pixel size.
    nonisolated static func pngAndSize(_ data: Data, type: NSPasteboard.PasteboardType) -> (Data, Int, Int)? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] else { return nil }
        let w = props[kCGImagePropertyPixelWidth] as? Int ?? 0, h = props[kCGImagePropertyPixelHeight] as? Int ?? 0
        if type == .png { return (data, w, h) }
        guard let img = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return nil }
        let out = NSMutableData()
        guard let dst = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dst, img, nil)
        guard CGImageDestinationFinalize(dst) else { return nil }
        return (out as Data, w, h)
    }

    // MARK: Panel

    private func buildUI() {
        panel.setContentSize(NSSize(width: ClipTheme.width, height: ClipTheme.height))
        field.frame = NSRect(x: 22, y: (Theme.fieldHeight - 34) / 2, width: ClipTheme.width - 44, height: 34)
        field.placeholderString = "Clipboard"
        field.delegate = self
        panel.content.addSubview(field)
        list.frame.origin = NSPoint(x: 0, y: Theme.fieldHeight)
        panel.content.addSubview(list)
        preview.frame = NSRect(x: ClipTheme.listWidth + 4, y: Theme.fieldHeight + 2,
                               width: ClipTheme.width - ClipTheme.listWidth - 18,
                               height: ClipTheme.height - Theme.fieldHeight - 14)
        panel.content.addSubview(preview)
        let sep = NSBox(frame: NSRect(x: 0, y: Theme.fieldHeight - 1, width: ClipTheme.width, height: 1))
        sep.boxType = .separator
        panel.content.addSubview(sep)
        panel.onResignKey = { [weak self] in self?.hide() }
        panel.keyHandler = { [weak self] e in self?.handleKeyEquivalent(e) ?? false }
        list.onClick = { [weak self] i in
            guard let self else { return }
            self.selected = self.offset + i
            self.paste(self.selected, andPaste: true)
        }
    }

    func toggle() { panel.isVisible ? hide() : show() }

    func show() {
        field.stringValue = ""
        refresh()
        panel.position(height: ClipTheme.height)
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(field)
    }

    func hide() { if panel.isVisible { panel.orderOut(nil) } }

    func controlTextDidChange(_ obj: Notification) { refresh() }

    private func refresh() {
        let t0 = nowNanos()
        results = store.search(field.stringValue, limit: 500)
        selected = 0
        offset = 0
        render()
        searchLatency.add(nowNanos() - t0)
    }

    private func render() {
        let end = min(results.count, offset + ClipTheme.visibleRows)
        var rows: [ResultList.Row] = []
        let now = UInt32(Date().timeIntervalSince1970)
        for r in results[offset..<end] {
            rows.append(.init(title: title(r), detail: ago(now, store.time[r]), icon: .atlas(icon(r))))
        }
        list.set(rows, selected: selected - offset)
        preview.show(results.isEmpty ? nil : results[selected], store: store, engine: engine)
    }

    private func title(_ i: Int) -> String {
        switch store.kind[i] {
        case .image: return store.text(i)
        case .files:
            let paths = store.text(i).split(separator: "\n")
            let first = (paths.first.map { String($0) } ?? "") as NSString
            return paths.count == 1 ? first.lastPathComponent : "\(first.lastPathComponent) + \(paths.count - 1) more"
        case .text:
            return ClipText.firstLine(store, i)
        }
    }

    private func icon(_ i: Int) -> Int32 {
        if let a = store.app(i), let s = engine.appSlot(bundleID: a) { return s }
        switch store.kind[i] {
        case .text: return engine.slot(.text)
        case .image: return engine.slot(.image)
        case .files: return engine.slot(.files)
        }
    }

    private func ago(_ now: UInt32, _ t: UInt32) -> String {
        let d = Int(now > t ? now - t : 0)
        if d < 60 { return "now" }
        if d < 3600 { return "\(d / 60)m" }
        if d < 86400 { return "\(d / 3600)h" }
        return "\(d / 86400)d"
    }

    private func move(_ delta: Int) {
        guard !results.isEmpty else { return }
        selected = max(0, min(results.count - 1, selected + delta))
        if selected < offset { offset = selected }
        if selected >= offset + ClipTheme.visibleRows { offset = selected - ClipTheme.visibleRows + 1 }
        render()
    }

    func control(_ control: NSControl, textView: NSTextView, doCommandBy sel: Selector) -> Bool {
        switch sel {
        case #selector(NSResponder.moveDown(_:)): move(1); return true
        case #selector(NSResponder.moveUp(_:)): move(-1); return true
        case #selector(NSResponder.pageDown(_:)), #selector(NSResponder.scrollPageDown(_:)): move(ClipTheme.visibleRows); return true
        case #selector(NSResponder.pageUp(_:)), #selector(NSResponder.scrollPageUp(_:)): move(-ClipTheme.visibleRows); return true
        case #selector(NSResponder.insertNewline(_:)):
            paste(selected, andPaste: !NSEvent.modifierFlags.contains(.command))
            return true
        case #selector(NSResponder.cancelOperation(_:)): hide(); return true
        default: return false
        }
    }

    /// ⌘1…⌘9 paste a visible row; ⌘↩ copy without pasting; ⌘⌫ delete the clip.
    private func handleKeyEquivalent(_ e: NSEvent) -> Bool {
        let mods = e.modifierFlags.intersection(.deviceIndependentFlagsMask)
        guard mods.contains(.command) else { return false }
        if let ch = e.charactersIgnoringModifiers, let d = Int(ch), d >= 1, d <= 9 {
            let i = offset + d - 1
            if i < results.count { paste(i, andPaste: true) }
            return true
        }
        switch e.keyCode {
        case 36, 76: paste(selected, andPaste: false); return true
        case 51:
            guard selected < results.count else { return true }
            store.delete(results[selected])
            let keep = selected
            results = store.search(field.stringValue, limit: 500)
            selected = min(keep, max(0, results.count - 1))
            offset = min(offset, selected)
            render()
            return true
        default: return false
        }
    }

    // MARK: Paste

    /// Puts clip `ri` (index into results) on the pasteboard and, if asked, pastes it into
    /// the app that was frontmost — which is still frontmost, since the panel never
    /// activated Fred.
    private func paste(_ ri: Int, andPaste: Bool) {
        guard ri >= 0, ri < results.count else { return }
        let i = results[ri]
        let pb = NSPasteboard.general
        pb.clearContents()
        switch store.kind[i] {
        case .text: pb.setString(store.text(i), forType: .string)
        case .files:
            let urls = store.text(i).split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pb.writeObjects(urls)
        case .image:
            if let u = store.imageURL(store.hash[i]), let d = try? Data(contentsOf: u) {
                pb.setData(d, forType: .png)
                if let tiff = NSImage(data: d)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        }
        lastChange = pb.changeCount          // our own write: don't re-capture
        store.touch(i, time: UInt32(Date().timeIntervalSince1970))
        hide()
        if andPaste {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.03) { Actions.postPaste() }
        }
    }

    // MARK: Control socket

    var statsLine: String { "clipboard: \(store.stats); \(searchLatency.summary)" }

    func control(_ arg: String) -> String {
        let parts = arg.split(separator: " ", maxSplits: 1).map(String.init)
        switch parts.first {
        case "search":
            let q = parts.count > 1 ? parts[1] : ""
            let t0 = nowNanos()
            let r = store.search(q, limit: 20)
            var s = "\(r.count) in \((nowNanos() - t0) / 1000) µs\n"
            for i in r { s += "  \(store.kind[i]) \(store.app(i) ?? "-") | \(ClipText.firstLine(store, i))\n" }
            return s
        case "forget":
            // Deletes every clip matching a query (maintenance: remove test clips).
            guard parts.count > 1, !parts[1].isEmpty else { return "usage: clip forget <query>" }
            let r = store.search(parts[1], limit: 1000)
            for i in r.sorted(by: >) { store.delete(i) }
            return "deleted \(r.count)"
        case "show": show(); return "ok"
        case "snapshot":
            guard parts.count > 1 else { return "usage: clip snapshot <png> [query]" }
            let bits = parts[1].split(separator: " ", maxSplits: 1).map(String.init)
            let was = panel.isVisible
            if !was { panel.alphaValue = 0; panel.position(height: ClipTheme.height); panel.orderFrontRegardless() }
            field.stringValue = bits.count > 1 ? bits[1] : ""
            refresh()
            let r = Snapshot.write(view: panel.glass, to: bits[0])
            if !was { panel.orderOut(nil); panel.alphaValue = 1 }
            return r
        default: return "clip: search <q> | show | snapshot <png> [q]"
        }
    }
}

enum ClipTheme {
    static let width: CGFloat = 860
    static let listWidth: CGFloat = 380
    static let rowHeight: CGFloat = 42
    static let visibleRows = 10
    static let height: CGFloat = Theme.fieldHeight + CGFloat(visibleRows) * rowHeight + 12
}

enum ClipText {
    /// First non-empty line, whitespace-collapsed, capped — computed only for visible rows.
    @MainActor static func firstLine(_ store: ClipStore, _ i: Int) -> String {
        let s = store.text(i)
        var out = ""
        for line in s.split(whereSeparator: \.isNewline) {
            let t = line.trimmingCharacters(in: .whitespaces)
            if !t.isEmpty { out = String(t.prefix(300)); break }
        }
        return out.isEmpty ? "(whitespace)" : out
    }
}

/// Right-hand preview: full text (scrollable) or the image.
@MainActor
final class ClipPreview: FlippedView {
    private let scroll = NSScrollView()
    private let textView = NSTextView()
    private let imageView = NSImageView()
    private let meta = NSTextField(labelWithString: "")
    private var shown: (Int, UInt64)?

    override init(frame: NSRect) {
        super.init(frame: frame)
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.borderType = .noBorder
        scroll.autohidesScrollers = true
        textView.isEditable = false
        textView.isSelectable = true
        textView.drawsBackground = false
        textView.font = .monospacedSystemFont(ofSize: 12, weight: .regular)
        textView.textContainerInset = NSSize(width: 8, height: 8)
        textView.isVerticallyResizable = true
        textView.autoresizingMask = [.width]
        textView.textContainer?.widthTracksTextView = true
        scroll.documentView = textView
        addSubview(scroll)
        imageView.imageScaling = .scaleProportionallyDown
        imageView.imageAlignment = .alignCenter
        addSubview(imageView)
        meta.font = .systemFont(ofSize: 11)
        meta.textColor = .secondaryLabelColor
        addSubview(meta)
    }

    required init?(coder: NSCoder) { fatalError() }

    override func layout() {
        super.layout()
        let body = NSRect(x: 0, y: 0, width: bounds.width, height: bounds.height - 22)
        scroll.frame = body
        imageView.frame = body.insetBy(dx: 8, dy: 8)
        meta.frame = NSRect(x: 8, y: bounds.height - 18, width: bounds.width - 16, height: 16)
    }

    func show(_ i: Int?, store: ClipStore, engine: Engine) {
        guard let i else { textView.string = ""; imageView.image = nil; meta.stringValue = ""; shown = nil; return }
        let key = (i, store.hash[i])
        if let s = shown, s.0 == key.0 && s.1 == key.1 { return }
        shown = key
        let date = Date(timeIntervalSince1970: TimeInterval(store.time[i]))
        let app = store.app(i).flatMap { engine.appName(bundleID: $0) } ?? store.app(i) ?? ""
        let df = DateFormatter()
        df.dateStyle = .medium
        df.timeStyle = .short
        switch store.kind[i] {
        case .image:
            scroll.isHidden = true
            imageView.isHidden = false
            imageView.image = store.imageURL(store.hash[i]).flatMap { NSImage(contentsOf: $0) }
            meta.stringValue = [store.text(i), app, df.string(from: date)].filter { !$0.isEmpty }.joined(separator: " · ")
        case .text, .files:
            imageView.isHidden = true
            imageView.image = nil
            scroll.isHidden = false
            var s = store.text(i)
            if s.utf8.count > 200_000 { s = String(s.prefix(200_000)) + "\n…" }
            textView.string = s
            textView.scroll(.zero)
            let chars = store.kind[i] == .text ? "\(store.text(i).count) chars" : "files"
            meta.stringValue = [chars, app, df.string(from: date)].filter { !$0.isEmpty }.joined(separator: " · ")
        }
    }
}
